/** 문구를 섞고 새 목록의 첫 문구가 직전 문구와 같으면 순서를 바꾼다. */
export function shuffleRestQuotes(previousQuote: string | null): string[] {
  const quotes = [...REST_QUOTES];
  for (let i = quotes.length - 1; i > 0; i--) {
    const randomIndex = Math.floor(Math.random() * (i + 1));
    [quotes[i], quotes[randomIndex]] = [quotes[randomIndex], quotes[i]];
  }
  const last = quotes.length - 1;
  if (quotes[last] === previousQuote) {
    [quotes[0], quotes[last]] = [quotes[last], quotes[0]];
  }
  return quotes;
}
